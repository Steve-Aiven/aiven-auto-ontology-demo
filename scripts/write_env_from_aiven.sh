#!/usr/bin/env bash
# Generate a starter .env from Aiven service connection info.
# You must still set AIVEN_AI_GATEWAY_API_KEY and OS_EMBED_MODEL_ID.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
export AIVEN_PROJECT="${AIVEN_PROJECT:-shutchinson-demo}"
export PG_SERVICE="${PG_SERVICE:-ao-pg}"
export OS_SERVICE="${OS_SERVICE:-ao-opensearch}"
export ENV_OUT="${ROOT}/.env"

avn project switch "${AIVEN_PROJECT}" >/dev/null

python3 <<'PY'
import json, os, secrets, subprocess, pathlib

project = os.environ["AIVEN_PROJECT"]
pg = os.environ["PG_SERVICE"]
osvc = os.environ["OS_SERVICE"]
out = pathlib.Path(os.environ["ENV_OUT"])

def svc(name):
    raw = subprocess.check_output(
        ["avn", "service", "get", name, "--project", project, "--json"],
        text=True,
    )
    return json.loads(raw)

pg_i = (svc(pg).get("service_uri_params") or {})
os_i = (svc(osvc).get("service_uri_params") or {})

pg_user = pg_i.get("user", "avnadmin")
pg_pass = pg_i.get("password", "")
pg_host = pg_i.get("host", "")
pg_port = pg_i.get("port", "5432")
pg_db = pg_i.get("dbname", "defaultdb")

os_user = os_i.get("user", "avnadmin")
os_pass = os_i.get("password", "")
os_host = os_i.get("host", "")
os_port = os_i.get("port", "443")

conn = f"postgresql://{pg_user}:{pg_pass}@{pg_host}:{pg_port}/saas_analytics?sslmode=require"

existing = {}
if out.exists():
    for line in out.read_text().splitlines():
        if not line or line.startswith("#") or "=" not in line:
            continue
        k, _, v = line.partition("=")
        existing[k] = v

gateway = existing.get("AIVEN_AI_GATEWAY_API_KEY", "")
model_id = existing.get("OS_EMBED_MODEL_ID", "")
auth = existing.get("AUTH_SECRET") or secrets.token_urlsafe(32)

content = f"""# Generated by scripts/write_env_from_aiven.sh
AIVEN_AI_GATEWAY_API_KEY={gateway}
DEFAULT_MODELS_API_KEY={gateway}
DEFAULT_MODELS_ENDPOINT=https://ai.aiven.io/v1
DEFAULT_MODELS_MODEL=nemotron-nano-3-30b
REASONING_API_KEY={gateway}
REASONING_ENDPOINT=https://ai.aiven.io/v1
REASONING_MODEL=nemotron-nano-3-30b
NON_REASONING_API_KEY={gateway}
NON_REASONING_ENDPOINT=https://ai.aiven.io/v1
NON_REASONING_MODEL=nemotron-nano-9b-v2

EMBED_API_KEY=unused
EMBED_ENDPOINT=http://os-embed-shim:8080/v1
EMBED_MODEL=os-embed

APP_URL=http://localhost:3000
AUTO_ONTOLOGY_MCP_PUBLIC_URL=http://localhost:3003
AUTH_SECRET={auth}
AUTO_ONTOLOGY_ADMIN_EMAIL={existing.get("AUTO_ONTOLOGY_ADMIN_EMAIL", "admin@example.com")}
AUTO_ONTOLOGY_ADMIN_PASSWORD={existing.get("AUTO_ONTOLOGY_ADMIN_PASSWORD", "autoontologypassword123")}
PYTHON_API_URL=http://auto-ontology:3001
INGESTION_SERVICE_URL=http://ingestion-service:3002

POSTGRES_HOST={pg_host}
POSTGRES_PORT={pg_port}
POSTGRES_USER={pg_user}
POSTGRES_PASSWORD={pg_pass}
POSTGRES_DATABASE={pg_db}
POSTGRES_SSLMODE=require

CONNECTION_STRINGS={conn}

OPENSEARCH_URL=https://{os_host}:{os_port}
OPENSEARCH_USER={os_user}
OPENSEARCH_PASSWORD={os_pass}
OPENSEARCH_SSL_VERIFY=false
OS_EMBED_MODEL_ID={model_id}
OS_EMBED_DIMS=384
"""
out.write_text(content)
print(f"Wrote {out}")
if not gateway:
    print("WARNING: set AIVEN_AI_GATEWAY_API_KEY in .env (AI Gateway tab in console)")
if not model_id:
    print("WARNING: run scripts/deploy_os_embed_model.sh then paste OS_EMBED_MODEL_ID into .env")
PY
